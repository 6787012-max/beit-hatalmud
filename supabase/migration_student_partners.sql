-- שותפים בלמידה: איש צוות שמלווה תלמיד ספציפי (לא רק כיתה), עם תפקיד.
-- משמש את תל"א: ברשימת אנשי הצוות בעורך היעד מוצגים רק השותפים של התלמיד.
-- קריאה: מי שרשאי לראות את התלמיד (כמו תל"א). כתיבה: אותו כלל + my_write_ok().
-- anon חסום לחלוטין.
-- ═══════════════════════════════════════════════════════════════

create table if not exists public.student_partners (
  id          bigint generated by default as identity primary key,
  student_id  bigint not null references public.students(id) on delete cascade,
  staff_id    bigint not null references public.staff(id) on delete cascade,
  role        text,                                   -- מחנך | מטפל רגשי | מורה לקריאה | … | חופשי
  created_by  uuid references public.profiles(id) on delete set null,
  created_at  timestamptz not null default now(),
  unique (student_id, staff_id)
);
create index if not exists idx_student_partners_student on public.student_partners(student_id);

alter table public.student_partners enable row level security;

-- הרשאות טבלה: anon לא מקבל כלום (גם לא מ-PUBLIC שברירת המחדל של Supabase נותנת)
revoke all on public.student_partners from public, anon;
grant select, insert, update, delete on public.student_partners to authenticated;
grant usage, select on sequence public.student_partners_id_seq to authenticated;

drop policy if exists sp_read on public.student_partners;
create policy sp_read on public.student_partners for select to authenticated
  using (public.can_see_student(student_id));

drop policy if exists sp_ins on public.student_partners;
create policy sp_ins on public.student_partners for insert to authenticated
  with check (public.can_see_student(student_id) and public.my_write_ok());

drop policy if exists sp_upd on public.student_partners;
create policy sp_upd on public.student_partners for update to authenticated
  using (public.can_see_student(student_id) and public.my_write_ok())
  with check (public.can_see_student(student_id) and public.my_write_ok());

drop policy if exists sp_del on public.student_partners;
create policy sp_del on public.student_partners for delete to authenticated
  using (public.can_see_student(student_id) and public.my_write_ok());
