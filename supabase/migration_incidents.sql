-- migration_incidents.sql · "אירועים חריגים" (2026-11-12, בקשת יוסף)
--
-- מה זה פותר: אירוע תאונה אמיתי הוכנס ל-behavior_events כסוג "אחר", והקבצים
-- (סרטון ותמונות) הוצמדו לתלמיד ולא לאירוע. כאן לכל אירוע חריג יש רשומה משלו
-- (incidents) וקבצים שמשויכים אליו (incident_files).
--
-- מודל:
--   • incidents       — האירוע עצמו (תאונה / פציעה / אירוע רפואי / אלימות / אחר).
--                       מחיקה רכה בלבד: deleted_at / deleted_by. אין policy ל-DELETE.
--   • incident_files  — קובץ שמשויך לאירוע. הקובץ עצמו יושב ב-bucket הקיים
--                       student-docs, תחת נתיב {student_id}/{אקראי}-{שם}.
--
-- ⚠️ מוסכמת הנתיב היא חובה: ה-policy הקיים על storage.objects
--    (sdoc_obj_read / sdoc_obj_ins / sdoc_obj_del, ב-migration_student_docs.sql)
--    שולף את התיקייה הראשונה בנתיב כמזהה תלמיד. הבלוק הראשון בקובץ הזה בודק
--    שה-policies האלה קיימים, ואם לא — המיגרציה נכשלת במקום להשאיר קבצים לא נגישים.
--
-- הרשאות (מקביל ל-student_docs / behavior):
--   • קריאה: can_read_student (מנהל, או מי שרשאי לראות את כיתת התלמיד).
--   • הוספה: is_staff + can_read_student, והרשומה חייבת להיות של המשתמש עצמו.
--   • עדכון / מחיקה: מנהל, או היוצר. (מחיקה רכה של אירוע = עדכון deleted_at.)
--   • anon: אין כלום.
--
-- אידמפוטנטי — בטוח להריץ שוב.
-- ═══════════════════════════════════════════════════════════════

begin;

-- ===== בדיקת תנאים מוקדמים =====
-- הפונקציות והפוליסיות שהמיגרציה נשענת עליהן חייבות להיות קיימות.
do $$
begin
  if not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                  where n.nspname = 'public' and p.proname = 'can_read_student') then
    raise exception 'migration_incidents: חסרה הפונקציה can_read_student';
  end if;
  if not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                  where n.nspname = 'public' and p.proname = 'is_staff') then
    raise exception 'migration_incidents: חסרה הפונקציה is_staff';
  end if;
  if not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                  where n.nspname = 'public' and p.proname = 'is_admin') then
    raise exception 'migration_incidents: חסרה הפונקציה is_admin';
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'storage' and tablename = 'objects'
                   and policyname = 'sdoc_obj_read')
     or not exists (select 1 from pg_policies where schemaname = 'storage' and tablename = 'objects'
                   and policyname = 'sdoc_obj_ins') then
    raise exception 'migration_incidents: חסרות policies של storage.objects (sdoc_obj_*) — הרץ קודם migration_student_docs.sql';
  end if;
end $$;

-- ===== 1. האירוע =====
create table if not exists public.incidents (
  id              bigint generated by default as identity primary key,
  student_id      bigint not null references public.students(id) on delete cascade,
  incident_date   date   not null default ((now() at time zone 'Asia/Jerusalem')::date),
  incident_time   text,                                   -- HH:MM, לא חובה
  place           text,                                   -- מקום האירוע (חצר, כיתה, אוטובוס…)
  kind            text   not null default 'אחר',
  severity        text   not null default 'רגילה',
  description     text,                                   -- מה קרה
  injury          text,                                   -- פציעה / נזק שנגרם
  treated_by      text,                                   -- מי טיפל (מד"א, אחות, מורה…)
  parent_notified boolean not null default false,
  parent_note     text,                                   -- מתי ואיך עודכנו ההורים
  other_students  text,                                   -- תלמידים אחרים שהיו מעורבים / נכחו
  status          text   not null default 'פתוח',
  followup_note   text,                                   -- מה נעשה / מה נדרש בהמשך
  created_by      uuid default auth.uid() references public.profiles(id),
  created_at      timestamptz not null default now(),
  deleted_at      timestamptz,
  deleted_by      uuid,
  constraint incidents_kind_chk     check (kind in ('תאונה', 'פציעה', 'אירוע רפואי', 'אלימות', 'אחר')),
  constraint incidents_severity_chk check (severity in ('נמוכה', 'רגילה', 'גבוהה')),
  constraint incidents_status_chk   check (status in ('פתוח', 'סגור'))
);
create index if not exists incidents_student_idx on public.incidents(student_id);
create index if not exists incidents_date_idx    on public.incidents(incident_date desc);

alter table public.incidents enable row level security;

-- קריאה: מי שרשאי לראות את התלמיד. רשומה שנמחקה רכות נשארת גלויה רק למנהל וליוצר
-- (אחרת העדכון של deleted_at עצמו היה נכשל ב-RETURNING של הכתיבה).
drop policy if exists inc_read on public.incidents;
create policy inc_read on public.incidents for select to authenticated
  using ( public.can_read_student(student_id)
          and (deleted_at is null or public.is_admin() or created_by = auth.uid()) );

drop policy if exists inc_ins on public.incidents;
create policy inc_ins on public.incidents for insert to authenticated
  with check ( public.is_staff()
               and public.can_read_student(student_id)
               and (created_by is null or created_by = auth.uid()) );

-- עדכון (כולל מחיקה רכה): מנהל, או היוצר
drop policy if exists inc_upd on public.incidents;
create policy inc_upd on public.incidents for update to authenticated
  using ( public.is_admin() or created_by = auth.uid() )
  with check ( public.is_admin() or created_by = auth.uid() );

-- אין policy ל-DELETE, ואין grant ל-delete: מחיקה אמיתית של אירוע אסורה.
revoke all on table public.incidents from anon;
revoke all on table public.incidents from authenticated;
grant select, insert, update on table public.incidents to authenticated;
grant usage on sequence public.incidents_id_seq to authenticated;

-- ===== 2. קבצים שמשויכים לאירוע =====
create table if not exists public.incident_files (
  id          bigint generated by default as identity primary key,
  incident_id bigint not null references public.incidents(id) on delete cascade,
  student_id  bigint not null references public.students(id) on delete cascade,
  path        text   not null,                            -- ב-bucket student-docs: {student_id}/{אקראי}-{שם}
  title       text   not null,                            -- שם הקובץ המקורי, לתצוגה
  mime        text,
  size_bytes  bigint,
  created_by  uuid default auth.uid() references public.profiles(id),
  created_at  timestamptz not null default now(),
  constraint incident_files_path_uidx unique (path),
  -- התיקייה הראשונה בנתיב חייבת להיות מזהה התלמיד — אחרת ה-policy של Storage לא יאכוף הרשאה
  constraint incident_files_path_chk check (split_part(path, '/', 1) = student_id::text)
);
-- קבצים עד 10MB נשמרים כאן (base64) ולא ב-Storage: נטפרי חוסם הורדה בינארית מ-Storage
-- (סרטון הוחזר 418 ותמונות הוחלפו בממלא מקום). הנתיב של קובץ כזה הוא {student_id}/inline-…
-- כדי שה-constraint וה-policy יישארו תקפים. לקבצים מעל 10MB העמודה ריקה והקובץ ב-Storage.
alter table public.incident_files add column if not exists data_b64 text;

create index if not exists incident_files_incident_idx on public.incident_files(incident_id);
create index if not exists incident_files_student_idx  on public.incident_files(student_id);

alter table public.incident_files enable row level security;

drop policy if exists incf_read on public.incident_files;
create policy incf_read on public.incident_files for select to authenticated
  using ( public.can_read_student(student_id) );

-- הוספה: איש צוות פעיל שרשאי לראות את התלמיד, הקובץ נרשם בשמו, והאירוע שייך לאותו תלמיד
drop policy if exists incf_ins on public.incident_files;
create policy incf_ins on public.incident_files for insert to authenticated
  with check ( public.is_staff()
               and public.can_read_student(student_id)
               and (created_by is null or created_by = auth.uid())
               and exists (select 1 from public.incidents i
                            where i.id = incident_id and i.student_id = incident_files.student_id) );

-- עדכון / מחיקה: מנהל, או היוצר
drop policy if exists incf_upd on public.incident_files;
create policy incf_upd on public.incident_files for update to authenticated
  using ( public.is_admin() or created_by = auth.uid() )
  with check ( public.is_admin() or created_by = auth.uid() );

drop policy if exists incf_del on public.incident_files;
create policy incf_del on public.incident_files for delete to authenticated
  using ( public.is_admin() or created_by = auth.uid() );

revoke all on table public.incident_files from anon;
revoke all on table public.incident_files from authenticated;
grant select, insert, update, delete on table public.incident_files to authenticated;
grant usage on sequence public.incident_files_id_seq to authenticated;

-- ===== 3. Storage =====
-- ה-bucket וה-policies כבר נוצרו ב-migration_student_docs.sql ומכסים גם את הקבצים האלה,
-- כי הנתיב מתחיל במזהה התלמיד. כאן רק מוודאים שה-bucket קיים (לא משנים את הגדרותיו).
insert into storage.buckets (id, name, public)
  values ('student-docs', 'student-docs', false)
  on conflict (id) do nothing;

commit;
