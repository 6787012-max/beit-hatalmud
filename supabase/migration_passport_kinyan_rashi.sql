--
-- ציון איכותני (בעיקר א / א+), לא מספרי כמו שאר שדות הדרכון — ולכן text חופשי,
-- בלי CHECK על ערכים סגורים. הגיליון שממנו יובאו הנתונים הקיימים (מעקב ידני
-- של המלמדים לפני שהתווסף כאן) מוכיח שבפועל נכתבות גם דרגות נוספות (ב, ג)
-- וגם הערות חופשיות ("לא כתב כלום", "לבדוק", "דחוף" וכו') — לא רק א/א+.
-- תימחור לפי בקשת הרב וינברג: בדיוק 'א' = 1.5 ₪, בדיוק 'א+' = 2.5 ₪, כל
-- ערך אחר (כולל ריק) = 0 ₪. בלי השפעה על "ניקוד" השבוע (0–100 של ארבעת
-- השדות המקוריים) — משפיע רק על עמודת השכר, שזה כל מה שהתבקש.
--
-- הרשאות/מבנה: אותה טבלה, בלי שינוי ב-RLS הקיים. אידמפוטנטי.

alter table public.passport add column if not exists kinyan_rashi text;
alter table public.passport drop constraint if exists passport_kinyan_rashi_chk;
